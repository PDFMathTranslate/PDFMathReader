const makeLocale = (entries) => {
  const locale = {};
  for (const [path, value] of Object.entries(entries)) {
    const parts = path.split('.');
    let cursor = locale;
    for (let index = 0; index < parts.length - 1; index += 1) cursor = cursor[parts[index]] ??= {};
    cursor[parts[parts.length - 1]] = value;
  }
  return locale;
};

