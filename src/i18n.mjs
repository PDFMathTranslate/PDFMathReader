function lookup(locale, key) {
 let value = messages[locale];
 for (const part of String(key).split('.')) {
  if (!value || typeof value !== 'object' || !(part in value)) return undefined;
  value = value[part];
 }
 return value;
}

function supportedLanguage(code) {
 return SUPPORTED_UI_LANGUAGES.includes(code) ? code : 'en';
}

export function setUILanguage(code) {
 uiLanguage.value = supportedLanguage(code);
 const documentElement = globalThis.document?.documentElement;
 if (documentElement) documentElement.lang = uiLanguage.value;
 return uiLanguage.value;
}

export function t(key, params = {}) {
 const localized = lookup(uiLanguage.value, key);
 const fallback = lookup('en', key);
 const value = typeof localized === 'string' ? localized : typeof fallback === 'string' ? fallback : String(key);
 const values = params && typeof params === 'object' ? params : {};
 return value.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name) => Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}
