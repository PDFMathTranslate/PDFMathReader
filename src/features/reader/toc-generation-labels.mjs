export function tocGenerationLabel(key, params = {}, language = uiLanguage.value) {
  const text = labels[language]?.[key] ?? labels.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => String(params[name] ?? match));
}
